    private const TAGS = [
        'general' => 'عام', 'fashion' => 'ملابس', 'accessories' => 'إكسسوارات', 'perfumes' => 'عطور',
        'electronics' => 'إلكترونيات', 'beauty' => 'مستحضرات تجميل', 'home' => 'منزل', 'food' => 'أكل',
    ];

    public function run(): void
    {
        $order = 0;
        foreach (self::TAGS as $slug => $name) {
            ThemeTag::query()->firstOrCreate(['slug' => $slug], ['name' => $name, 'sort_order' => ++$order]);
        }

        foreach (self::THEMES as $theme) {
            $existing = Theme::query()->find($theme['key']);

            if ($existing === null) {
                $existing = Theme::create(['key' => $theme['key'], 'name' => $theme['name'], 'kind' => $theme['kind'], 'sort_order' => $theme['sort_order'], 'is_active' => true]);
            } else {
                // Keep the admin's is_active choice; refresh name, order and the kind (it belongs to the code).
                $existing->update(['name' => $theme['name'], 'kind' => $theme['kind'], 'sort_order' => $theme['sort_order']]);
            }

            // First time only: the store details (afterwards they belong to the admin).
            if ($existing->short_description === null && ! $existing->is_listed) {
                $existing->update([
                    'price' => $theme['price'],
                    'is_listed' => $theme['listed'] ?? true,
                    'released_at' => now(),
                    'version' => '1.0',
                ]);
                self::writeCopy($existing, $theme);
            }
        }
    }

    /**
     * The texts and tags of a shipped theme (never its price, listing or images).
     *
     * @param  array<string, mixed>  $theme  a row of THEMES
     */
    public static function writeCopy(Theme $model, array $theme): void
    {
        $model->update(['short_description' => $theme['short_description'], 'description' => $theme['description'], 'features' => $theme['features']]);
        $model->tags()->sync(ThemeTag::query()->whereIn('slug', $theme['tags'])->pluck('id')->all());
    }
